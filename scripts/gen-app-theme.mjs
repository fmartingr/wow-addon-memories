// Makes app/lib/src/theme/tokens.dart from the design tokens of the website: the colours of :root in web/base.css and
// the class and quality colours of web/lib/format.mjs. With --check it writes nothing and fails when the file is old.
// Usage: node scripts/gen-app-theme.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'app/lib/src/theme/tokens.dart');

export const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
export const dartColour = (hex) => `Color(0xFF${hex.slice(1).toUpperCase()})`;

// The colour tokens of :root, as { name: '#rrggbb' } in file order.
export function cssColours(css) {
  const block = /:root\s*\{([^}]*)\}/.exec(css)?.[1] ?? '';
  const colours = {};
  for (const m of block.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) {
    const value = m[2].trim();
    if (/^#[0-9a-fA-F]{6}$/.test(value)) colours[m[1]] = value.toLowerCase();
    else if (/^(#|rgb|hsl)/i.test(value)) throw new Error(`--${m[1]}: ${value} is not a 6 digit hex colour; the app tokens cannot hold it. Use #rrggbb.`);
  }
  return colours;
}

// The first family of a font token such as --display: Cinzel, Georgia, serif.
export function cssFamily(css, token) {
  const m = new RegExp(`--${token}:\\s*([^;]+);`).exec(css);
  return m ? m[1].split(',')[0].trim().replace(/^['"]|['"]$/g, '') : null;
}

export function listColours(js, name) {
  const body = new RegExp(`const ${name} = (\\{[^}]*\\}|\\[[^\\]]*\\])`).exec(js)?.[1] ?? '';
  return [...body.matchAll(/(?:([A-Z]+):\s*)?'(#[0-9a-fA-F]{6})'/g)].map((m) => [m[1] ?? null, m[2].toLowerCase()]);
}

export function generate(css, formatJs) {
  const colours = cssColours(css);
  const classes = listColours(formatJs, 'CLASS_COLOURS');
  const quality = listColours(formatJs, 'QUALITY_COLOURS');
  const lines = [
    '// Generated by scripts/gen-app-theme.mjs from web/base.css and web/lib/format.mjs. Do not edit by hand.',
    '// Run `make app-theme` after a change of the website tokens.',
    '',
    "import 'dart:ui' show Color;",
    '',
    '/// The design tokens of the website (the `:root` colours of `web/base.css`).',
    'abstract final class Tokens {',
  ];
  for (const [name, hex] of Object.entries(colours)) lines.push(`  static const Color ${camel(name)} = ${dartColour(hex)};`);
  lines.push('', `  static const String displayFamily = '${cssFamily(css, 'display')}';`, `  static const String bodyFamily = '${cssFamily(css, 'body')}';`, '}', '');
  lines.push('/// The class colours of the game, by class token such as `HUNTER`.', 'const Map<String, Color> classColours = {');
  for (const [k, hex] of classes) lines.push(`  '${k}': ${dartColour(hex)},`);
  lines.push('};', '', '/// The item quality colours, from poor (0) to legendary (5).', 'const List<Color> qualityColours = [');
  for (const [, hex] of quality) lines.push(`  ${dartColour(hex)},`);
  lines.push('];', '');
  return lines.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate(readFileSync(join(root, 'web/base.css'), 'utf8'), readFileSync(join(root, 'web/lib/format.mjs'), 'utf8'));
  if (process.argv.includes('--check')) {
    let have = '';
    try {
      have = readFileSync(out, 'utf8');
    } catch {}
    if (have !== text) {
      console.error('app/lib/src/theme/tokens.dart is not up to date. Run: make app-theme');
      process.exit(1);
    }
    console.log('app theme tokens are up to date');
  } else {
    writeFileSync(out, text);
    console.log('wrote app/lib/src/theme/tokens.dart');
  }
}
