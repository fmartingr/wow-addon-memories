local wow = require("helpers.wow")

describe("codec", function()
	local Codec

	before_each(function()
		local ns = wow.boot({ login = false })
		Codec = ns.Codec
	end)

	describe("Field", function()
		it("encodes nil, booleans, numbers and strings", function()
			assert.equal("", Codec.Field(nil))
			assert.equal("1", Codec.Field(true))
			assert.equal("0", Codec.Field(false))
			assert.equal("42", Codec.Field(42))
			assert.equal("-1.5", Codec.Field(-1.5))
			assert.equal("Minería", Codec.Field("Minería"))
		end)

		it("replaces | with / and each control character with a space", function()
			assert.equal("a/b", Codec.Field("a|b"))
			assert.equal("a b c d e", Codec.Field("a\nb\rc\0d\127e"))
			assert.equal("x  y", Codec.Field("x\t\31y"))
		end)
	end)

	describe("EncodeLine", function()
		it("joins the fixed columns, the kind and the fields", function()
			assert.equal("100|5|1453|10|20|lv|11", Codec.EncodeLine(100, 5, 1453, 10, 20, "lv", 11))
		end)

		it("keeps nil fields between set fields and drops trailing empty ones", function()
			assert.equal(
				"100|||||xp|50||Kobold",
				Codec.EncodeLine(100, nil, nil, nil, nil, "xp", 50, nil, "Kobold", nil, "")
			)
			assert.equal("100|||||out", Codec.EncodeLine(100, nil, nil, nil, nil, "out", nil, nil))
		end)

		it("escapes fields so that a line never holds an extra separator or line break", function()
			local line = Codec.EncodeLine(1, nil, nil, nil, nil, "ex", "src|x", "a\nb", "c\rd")
			assert.equal("1|||||ex|src/x|a b|c d", line)
			assert.is_nil(line:find("\n"))
		end)
	end)

	describe("DecodeLine", function()
		it("round trips each field type", function()
			local line = Codec.EncodeLine(1793560500, 3600, 1453, 5000, 2500, "de", "Hogger", 448, nil, nil, "Elwynn")
			local ev = Codec.DecodeLine(line)
			assert.equal(1793560500, ev.t)
			assert.equal(3600, ev.p)
			assert.equal(1453, ev.m)
			assert.equal(5000, ev.x)
			assert.equal(2500, ev.y)
			assert.equal("de", ev.k)
			assert.equal("Hogger", ev.killer)
			assert.equal(448, ev.npc)
			assert.is_nil(ev.spell)
			assert.equal("Elwynn", ev.place)
			assert.same({ "Hogger", "448", "", "", "Elwynn" }, ev.raw)
		end)

		it("decodes numeric fields as numbers and booleans as 1 and 0", function()
			local ev = Codec.DecodeLine(Codec.EncodeLine(1, nil, nil, nil, nil, "bo", "Van Cleef", 1131, true, false))
			assert.equal("Van Cleef", ev.name)
			assert.equal(1131, ev.encounter)
			assert.equal(1, ev.success)
			assert.equal("0", ev.last)
			assert.is_nil(ev.seconds)
		end)

		it("decodes a numeric field that is not a number as nil and keeps it in raw", function()
			local ev = Codec.DecodeLine("1|||||lv|ten")
			assert.is_nil(ev.level)
			assert.same({ "ten" }, ev.raw)
		end)

		it("leaves the fixed columns nil when they are empty", function()
			local ev = Codec.DecodeLine("1|||||gh")
			assert.equal(1, ev.t)
			assert.is_nil(ev.p)
			assert.is_nil(ev.m)
			assert.equal("gh", ev.k)
			assert.same({}, ev.raw)
		end)

		it("keeps only raw fields for an unknown kind", function()
			local ev = Codec.DecodeLine("1|||||qq|a|b")
			assert.equal("qq", ev.k)
			assert.same({ "a", "b" }, ev.raw)
		end)
	end)
end)
